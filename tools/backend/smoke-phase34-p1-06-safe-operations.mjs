import {P103_REAL_DELIVERY_LOCKED} from '../../server/src/mail/mail-dynoweb-dispatcher.mjs';
let n=0;
const ok=(x,label)=>{assert.ok(x,label);n++};
const eq=(a,b,label)=>{assert.deepEqual(a,b,label);n++};
const source=(f)=>readFileSync(new URL('../../'+f,import.meta.url),'utf8');
const migration=source('server/migrations/047_phase34_p1_06_mail_retry_operations.sql');
ok(migration.includes("action IN ('cancel','retry')"),'retry audit constraint');
ok(!/CREATE DATABASE|CREATE EXTENSION|CREATE TABLE|CREATE INDEX/i.test(migration),'no new resources');
eq(P103_REAL_DELIVERY_LOCKED,true,'real sending locked');
const startup=source('server/src/index.mjs');
ok(startup.includes("P109_OPERATOR_CONTROL_ENABLED==='true'") && startup.includes("MAIL_ENABLED==='true'"),'schedule only after production operator and environment gates');
ok(!startup.includes('createP103Dispatcher'),'no live mail dispatcher');
const app=source('server/src/app.mjs');
for(const x of ["'/api/admin/mail-schedule/preview'","'/api/admin/mail-queue'",'mailQueueRetryMatch','admin_owner_required'])ok(app.includes(x),'owner route '+x);
const ui=source('src/admin/AdminMailNotificationsPanel.jsx');
for(const x of ['반납 알림 대상 확인','대상 확인','retryEligible','재처리'])ok(ui.includes(x),'UI '+x);
let called=[];
const pool={async query(sql,args=[]){called.push({sql,args});
 if(sql.includes('COUNT(*) FILTER'))return {rows:[{due_tomorrow:2,overdue:1}]};
 if(sql.trim().startsWith('SELECT payload FROM app_system_configuration'))return {rows:[{payload:{events:{rental_due_reminder:{enabled:true},rental_overdue:{enabled:false}}}}]};
 if(sql.includes('ORDER BY o.created_at'))return {rows:[{id:12,event_key:'rental_due_reminder',recipient_email:'member@example.com',state:'failed',last_error_code:'provider_rate_limited',safe_retry_candidate:true}]};
 if(sql.includes('GROUP BY state'))return {rows:[{state:'failed',total:1}]};
 if(sql.includes('WITH target AS'))return {rows:[{id:12}]};
 return {rows:[]};
},connect:async()=>{throw Error('preview must never request a transaction')}};
const preview=createP106ScheduledPreview(pool,{now:()=>new Date('2026-10-22T08:00:00Z')});
const result=await preview.preview();
eq(result.referenceDate,'2026-10-22','KST reference day');
eq(result.dueTomorrow,2,'due count');
eq(result.overdue,1,'overdue count');
eq(result.dueEnabled,true,'due event enabled');
eq(result.overdueEnabled,false,'overdue event disabled');
eq(result.readOnly,true,'read only');
ok(called.every(c=>/SELECT/i.test(c.sql)&&!/\b(UPDATE|DELETE|INSERT|COMMIT|BEGIN)\b/i.test(c.sql)),'read only SQL');
