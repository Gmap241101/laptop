ok(q.sql.includes("o.state='failed'"),'only failed');
ok(q.sql.includes("o.last_error_code IN ('provider_rate_limited','mail_attempts_exhausted')"),'only definitive 429');
ok(q.sql.includes("a.outcome='retry'"),'positive delivery attempt evidence');
