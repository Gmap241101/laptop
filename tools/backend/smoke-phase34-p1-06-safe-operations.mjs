ok(q.sql.includes('app_admin_identity_registry'),'admin recipient rechecked');
ok(q.sql.includes("'retry',$2"),'retry action audited');
ok(q.sql.includes("config.payload->'events'->o.event_key->>'enabled'='true'"),'event must be enabled');
await assert.rejects(()=>ops.retry({id:'0 OR true',actorClerkUserId:'user_abcdefghijk'}),/mail_queue_id_invalid/);n++;
await assert.rejects(()=>ops.retry({id:12,actorClerkUserId:'bad'}),/mail_actor_invalid/);n++;
const noResults={query:async(sql)=>({rows:sql.includes('WITH target AS')?[]:[]}),connect:async()=>{}};
await assert.rejects(()=>createMailQueueOperations(noResults).retry({id:12,actorClerkUserId:'user_abcdefghijk'}),/mail_queue_not_safely_retryable/);n++;
console.log(`[phase34-p1-06-safe-operations] PASS (${n} checks; no real sends, no automatic retry, read-only schedule preview)`);
