import assert from 'node:assert/strict';
import { existsSync, readFileSync } from 'node:fs';
const pkg = JSON.parse(readFileSync('package.json', 'utf8'));
assert.equal(pkg.dependencies?.firebase, undefined);
assert.equal(existsSync('src/firebase.js'), false, 'retired Firebase entrypoint must remain removed');
const config = readFileSync('src/features/auth/firebaseRuntimeRetirement.js', 'utf8');
const client = readFileSync('src/clerk/clerkStagingClient.js', 'utf8');
const auth = readFileSync('src/features/auth/useAdminAuthenticationController.js', 'utf8');
const data = readFileSync('src/features/settings/useAdminDataMaintenanceController.js', 'utf8');
assert.ok(config.includes("mode: 'removed'"), 'retirement should be explicit');
assert.equal(client.includes('X-Firebase-Authorization'), false, 'removed authorization header must stay removed');
assert.ok(auth.includes('clerk') || auth.includes('Clerk'), 'administrator authentication must still use Clerk');
assert.ok(data.includes('retiredOperation'), 'legacy direct restore must remain blocked');
assert.ok(data.includes('resetBackupReady'), 'destructive reset protection must remain present');
console.log('[phase34-runtime-retirement-frontend-smoke] PASS (Clerk-only authorization, retired Firebase SDK remains removed)');
